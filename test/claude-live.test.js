'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { itemsOf, toolLine, resultText, typedText, checkTranscript, projectFolder, createLive } = require('../src/main/claude/live');

const user = (content, extra = {}) => ({ type: 'user', message: { role: 'user', content }, ...extra });
const assistant = (content, extra = {}) => ({ type: 'assistant', message: { role: 'assistant', content }, ...extra });

test('what the person typed, Claude\'s replies, the tools it ran and what they gave back become items', () => {
  assert.deepStrictEqual(itemsOf(user('fix the login bug')), [{ kind: 'you', text: 'fix the login bug' }]);
  assert.deepStrictEqual(itemsOf(user([{ type: 'text', text: 'and add a test' }])), [{ kind: 'you', text: 'and add a test' }]);
  assert.deepStrictEqual(itemsOf(assistant([
    { type: 'thinking', thinking: 'hmm' },
    { type: 'text', text: '  I will look at it.  ' },
    { type: 'tool_use', name: 'Bash', input: { command: 'npm test\n  -- --watch' } },
  ])), [{ kind: 'claude', text: 'I will look at it.' }, { kind: 'tool', text: '$ npm test -- --watch' }]);
  assert.deepStrictEqual(itemsOf(user([{ type: 'tool_result', content: 'all 12 pass' }])), [{ kind: 'result', text: 'all 12 pass' }]);
  assert.deepStrictEqual(itemsOf(user([{ type: 'tool_result', content: [{ type: 'text', text: 'boom' }], is_error: true }])),
    [{ kind: 'result', text: 'boom', error: true }]);
  assert.deepStrictEqual(itemsOf(user('[Request interrupted by user]')), [{ kind: 'event', text: 'Stopped' }]);
});

test("a subagent's lines, Claude Code's own notes, other kinds of lines and anything malformed make no items", () => {
  for (const entry of [
    assistant([{ type: 'text', text: 'from a subagent' }], { isSidechain: true }),
    user('a note', { isMeta: true }),
    user('<system-reminder>be nice</system-reminder>'),
    user('<local-command-stdout>ok</local-command-stdout>'),
    user('Caveat: the messages below were generated by the user while running local commands.'),
    { type: 'attachment', attachment: {} },
    { type: 'summary', summary: 'x' },
    assistant([{ type: 'text', text: '   ' }]),
    user(null),
    null,
    'text',
    [],
  ]) {
    assert.deepStrictEqual(itemsOf(entry), [], JSON.stringify(entry));
  }
});

test('a slash command shows as the command the person typed', () => {
  assert.strictEqual(typedText('<command-name>/review</command-name><command-args>42</command-args>'), '/review 42');
  assert.strictEqual(typedText('<command-name>/clear</command-name><command-args></command-args>'), '/clear');
  assert.strictEqual(typedText('<command-name></command-name>'), null);
});

test("each tool's line says what it did in a few words", () => {
  assert.strictEqual(toolLine('Read', { file_path: '/Users/a/projects/app/src/main.js' }), 'Read src/main.js');
  assert.strictEqual(toolLine('Edit', { file_path: 'C:\\code\\app\\index.js' }), 'Edit app/index.js');
  assert.strictEqual(toolLine('Grep', { pattern: 'TODO' }), 'Grep TODO');
  assert.strictEqual(toolLine('WebSearch', { query: 'electron tray' }), 'Search electron tray');
  assert.strictEqual(toolLine('Agent', { description: 'Find the bug' }), 'Agent: Find the bug');
  assert.strictEqual(toolLine('TodoWrite', {}), 'Updated the to-do list');
  assert.strictEqual(toolLine('mcp__x__y', null), 'mcp__x__y');
  assert.strictEqual(toolLine(undefined, undefined), 'A tool');
  assert.ok(toolLine('Bash', { command: 'x'.repeat(500) }).length <= 201, 'a long command is cut');
});

test('what a tool gave back is cut to its first lines', () => {
  const long = Array.from({ length: 20 }, (_, i) => `line ${i + 1}`).join('\n');
  assert.strictEqual(resultText(long), `${long.split('\n').slice(0, 8).join('\n')}\n… 12 more lines`);
  assert.strictEqual(resultText([{ type: 'image' }, { type: 'text', text: 'a' }, { type: 'text', text: 'b' }]), 'a\nb');
  assert.strictEqual(resultText(undefined), '');
  assert.ok(resultText('y'.repeat(5000)).length <= 801);
});

