/** A Claude Code config folder in a temp folder, with one running session (this test's own process) and its file. */
function claudeHome(t, lines) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'buddy-live-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const cwd = '/Users/a/projects/shop';
  const id = '11111111-2222-3333-4444-555555555555';
  fs.mkdirSync(path.join(dir, 'sessions'));
  fs.writeFileSync(path.join(dir, 'sessions', `${process.pid}.json`), JSON.stringify({
    pid: process.pid, sessionId: id, cwd, name: 'shop-x', status: 'busy', kind: 'interactive', updatedAt: 1000,
  }));
  fs.writeFileSync(path.join(dir, 'sessions', '999999.json'), '{ not json');
  const transcript = path.join(dir, 'projects', projectFolder(cwd), `${id}.jsonl`);
  fs.mkdirSync(path.dirname(transcript), { recursive: true });
  fs.writeFileSync(transcript, lines.map((l) => JSON.stringify(l)).join('\n') + '\n');
  return { dir, id, cwd, transcript };
}

test('the sessions running now are found, with their terminal, and read from their start', async (t) => {
  const home = claudeHome(t, [user('hi'), assistant([{ type: 'text', text: 'Hello!' }])]);
  const live = createLive({ configDirs: () => [home.dir], now: () => 2000, ttys: async (pids) => ({ [pids[0]]: 'ttys004' }) });
  await live.discover();
  assert.deepStrictEqual(live.list(), [{ id: home.id, name: 'shop-x', title: null, status: 'working', canTalk: true }]);
  assert.deepStrictEqual(live.target(home.id), { tty: 'ttys004', name: 'shop-x' });

  const changed = [];
  live.onChange((id) => changed.push(id));
  await live.refresh(home.id);
  assert.deepStrictEqual(live.view(home.id).items, [{ id: 1, kind: 'you', text: 'hi' }, { id: 2, kind: 'claude', text: 'Hello!' }]);
  assert.deepStrictEqual(changed, [home.id]);

  // New lines: only they are read; a line still being written waits for its end.
  const tool = JSON.stringify(assistant([{ type: 'tool_use', name: 'Bash', input: { command: 'ls' } }]));
  fs.appendFileSync(home.transcript, `${tool}\n${tool.slice(0, 10)}`);
  await live.refresh(home.id);
  assert.deepStrictEqual(live.view(home.id).items.slice(2), [{ id: 3, kind: 'tool', text: '$ ls' }]);
  fs.appendFileSync(home.transcript, `${tool.slice(10)}\n`);
  await live.refresh(home.id);
  assert.strictEqual(live.view(home.id).items.length, 4);
  await live.refresh(home.id);
  assert.deepStrictEqual(changed, [home.id, home.id, home.id], 'nothing new: nobody is told');
});

